"""Generate docs/CALIBRATION_COVERAGE.md from the checked-in corpus and fit.

Every number in the generated document is computed from the same data
structures the planner loads at run time (OBSERVATIONS, CALIBRATED,
CALIBRATION_RESULTS, CLUSTERS) - nothing is hand-typed - so the document
cannot silently drift from the code.  Regenerate with:

    python3 studies/export_calibration_coverage.py

The checked-in document is enforced by tests/test_calibration_coverage.py.
Held-out uncertainty-interval coverage is tracked separately in
docs/UNCERTAINTY_COVERAGE.md.
"""
from __future__ import annotations

from collections import Counter
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from nomo_planner.domains.calibration import CALIBRATED, CALIBRATION_RESULTS, OBSERVATIONS  # noqa: E402
from nomo_planner.domains.hardware import CLUSTERS, MODELS, params  # noqa: E402


def _fmt_params(p: float) -> str:
    if p >= 1e12:
        return f"{p / 1e12:.3g}T"
    return f"{p / 1e9:.4g}B"


def coverage_facts() -> dict:
    """Compute the corpus facts from the live planner data structures."""
    model_keys = sorted({r["model"] for r in OBSERVATIONS})
    param_counts = {k: params(MODELS[k]) for k in model_keys}
    devices = sorted(int(r["devices"]) for r in OBSERVATIONS)
    batch = sorted(int(r["global_batch_tokens"]) for r in OBSERVATIONS)
    return {
        "rows": len(OBSERVATIONS),
        "source_counts": dict(sorted(Counter(r["source"] for r in OBSERVATIONS).items())),
        "url": OBSERVATIONS[0]["url"],
        "metric": sorted({r["metric"] for r in OBSERVATIONS}),
        "models": model_keys,
        "model_count": len(model_keys),
        "param_min": min(param_counts.values()),
        "param_max": max(param_counts.values()),
        "devices_min": devices[0],
        "devices_max": devices[-1],
        "tp": sorted({int(r["tp"]) for r in OBSERVATIONS}),
        "pp": sorted({int(r["pp"]) for r in OBSERVATIONS}),
        "zero": sorted({int(r["zero"]) for r in OBSERVATIONS}),
        "recompute": sorted({r["recompute"] for r in OBSERVATIONS}),
        "precisions": sorted({r["precision"] for r in OBSERVATIONS}),
        "seq_lens": sorted({int(r["seq_len"]) for r in OBSERVATIONS}),
        "batch_min": batch[0],
        "batch_max": batch[-1],
        "clusters_all": sorted(CLUSTERS),
        "clusters_calibrated": sorted(CALIBRATED),
        "per_cluster": {
            key: {"observations": CALIBRATED[key]["observations"],
                  "loo_mape_pct": CALIBRATED[key]["loo_mape_pct"]}
            for key in sorted(CALIBRATED)
        },
        "results": dict(CALIBRATION_RESULTS),
    }


def render_markdown(f: dict) -> str:
    src_table, table2 = f["source_counts"].get("Narayanan et al. 2021 Table 1", 0), \
        f["source_counts"].get("Narayanan et al. 2021 Table 2", 0)
    lines: list[str] = []
    lines.append("# Training-calibration coverage")
    lines.append("")
    lines.append("Generated by `studies/export_calibration_coverage.py` from `nomo_planner/domains/calibration.py`.")
    lines.append("Every number below is computed from the structures the planner loads at run time;")
    lines.append("regenerate instead of editing. Held-out uncertainty-interval coverage is tracked")
    lines.append("separately in [UNCERTAINTY_COVERAGE.md](UNCERTAINTY_COVERAGE.md).")
    lines.append("")
    lines.append("## Corpus")
    lines.append("")
    lines.append(f"- {f['rows']} measured observations, all from one publication: Narayanan et al. 2021,")
    lines.append(f"  \"Efficient Large-Scale Language Model Training on GPU Clusters Using Megatron-LM\"")
    lines.append(f"  ({f['url']}) - Table 1: {src_table} rows, Table 2: {table2} rows.")
    lines.append(f"- Metric: measured `{f['metric'][0]}` (step time derived with the paper's eq. 3).")
    lines.append(f"- Hardware: Selene DGX-A100 (`a100_nvlink_ib`) only. The other clusters in")
    lines.append(f"  `hardware.CLUSTERS` ({', '.join(c for c in f['clusters_all'] if c not in f['clusters_calibrated'])})")
    lines.append("  have no measured rows in this corpus.")
    lines.append(f"- Precision: {'/'.join(f['precisions'])} only. Sequence length: {'/'.join(str(s) for s in f['seq_lens'])} only.")
    lines.append(f"- Model size span: {_fmt_params(f['param_min'])} - {_fmt_params(f['param_max'])}"
                 f" ({f['model_count']} distinct Megatron GPT presets).")
    lines.append(f"- Device counts: {f['devices_min']} - {f['devices_max']}."
                 f" TP {{{','.join(str(t) for t in f['tp'])}}},"
                 f" PP {{{','.join(str(p) for p in f['pp'])}}},"
                 f" ZeRO {{{','.join(str(z) for z in f['zero'])}}}.")
    lines.append(f"- Global batch: {f['batch_min']:,} - {f['batch_max']:,} tokens.")
    lines.append("")
    lines.append("## Fit status per cluster")
    lines.append("")
    lines.append("| cluster | calibrated | measured rows | LOO MAPE |")
    lines.append("|---|---|---|---|")
    for key in f["clusters_all"]:
        if key in f["per_cluster"]:
            c = f["per_cluster"][key]
            lines.append(f"| {key} | yes | {c['observations']} | {c['loo_mape_pct']}% |")
        else:
            lines.append(f"| {key} | no | 0 | - |")
    lines.append("")
    r = f["results"]
    lines.append("## Accuracy evidence (from `CALIBRATION_RESULTS`)")
    lines.append("")
    lines.append(f"- held-out PTD-P MAPE: {r['held_out_ptd_mape']}% (Kendall {r['held_out_kendall']},"
                 f" Spearman {r['held_out_spearman']})")
    lines.append(f"- leave-one-out MAPE: {r['loo_mape']}%")
    lines.append(f"- ZeRO-3 transfer MAPE: {r['zero3_transfer_mape']}%")
    lines.append(f"- uncalibrated-cluster MAPE: {r['uncalibrated_mape']}%")
    lines.append("")
    lines.append("## Out-of-distribution use (read before trusting a prediction)")
    lines.append("")
    lines.append("Predictions outside this corpus rely on first-principles constants, not fitted")
    lines.append(f"coefficients; measured error there is ~{r['uncalibrated_mape']}% MAPE and unbounded beyond it.")
    lines.append("Do not treat planner outputs as calibrated for:")
    lines.append("")
    lines.append("- non-Selene clusters (H100, PCIe-only, TPU, or any other interconnect)")
    lines.append(f"- precision other than {'/'.join(f['precisions'])} (fp8-native training stacks, fp16, int8)")
    lines.append(f"- sequence lengths other than {'/'.join(str(s) for s in f['seq_lens'])}"
                 " and context-extended recipes (RoPE scaling, long-context attention variants)")
    lines.append("- architectures that are not dense GPT-style decoders (MoE, encoders, multimodal)")
    lines.append(f"- global batch shapes far outside {f['batch_min']:,} - {f['batch_max']:,} tokens")
    lines.append("")
    lines.append("## Extending the corpus honestly")
    lines.append("")
    lines.append("1. Add measured rows (CSV or JSON) with a citable `source_url`/DOI. The ingestors in")
    lines.append("   `nomo_planner/simcalibration.py` (`load_evidence`, `parse_evidence_csv`,")
    lines.append("   `parse_evidence_json`) reject rows without provenance and require ISO source dates.")
    lines.append("2. Fit with `fit_parameters` / `fit_by_strategy` and quantify with `evaluate_held_out`")
    lines.append("   (group-preserving train/held-out split, no leakage; see `tests/test_simcalibration.py`).")
    lines.append("3. A new cluster needs its own measured rows before the pack reports calibrated")
    lines.append("   accuracy; until then outputs stay on first-principles constants and are labelled")
    lines.append("   as uncalibrated.")
    lines.append("")
    return "\n".join(lines)


def main() -> None:
    doc = ROOT / "docs" / "CALIBRATION_COVERAGE.md"
    doc.write_text(render_markdown(coverage_facts()), encoding="utf-8")
    print(f"wrote {doc}")


if __name__ == "__main__":
    main()
